CREATE TABLE IF NOT EXISTS public.messenger_activities (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  conversation_id uuid NOT NULL REFERENCES public.conversations(id) ON DELETE CASCADE,
  game_type text NOT NULL CHECK (game_type IN (
    'tictactoe','checkers','mines','solitaire','connect4','chess','colourclash','match3','sudoku','words'
  )),
  inviter_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  opponent_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  status text NOT NULL DEFAULT 'invited' CHECK (status IN ('invited','active','declined','finished')),
  seed int NOT NULL DEFAULT floor(random()*1000000000)::int,
  turn_id uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  winner_id uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  move_number int NOT NULL DEFAULT 0 CHECK (move_number BETWEEN 0 AND 2000),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (inviter_id <> opponent_id)
);
CREATE INDEX IF NOT EXISTS activities_conversation_recent ON public.messenger_activities(conversation_id,created_at DESC);
