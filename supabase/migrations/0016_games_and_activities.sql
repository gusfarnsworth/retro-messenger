CREATE OR REPLACE FUNCTION public.messenger_invite_game(p_conversation uuid,p_game_type text,p_opponent uuid)
RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $fn$
DECLARE v_me uuid := auth.uid(); v_room uuid; v_kind text := lower(btrim(coalesce(p_game_type,''))); v_mines int[];
BEGIN
 IF v_me IS NULL OR NOT public.is_member(p_conversation,v_me) OR NOT public.is_member(p_conversation,p_opponent)
    OR p_opponent IS NULL OR p_opponent=v_me OR NOT public.can_message(p_conversation,v_me) OR NOT public.can_message(p_conversation,p_opponent)
 THEN RAISE EXCEPTION 'Both players must be members of the conversation' USING ERRCODE='42501'; END IF;
 IF v_kind NOT IN ('tictactoe','checkers','mines','solitaire','connect4','chess','colourclash','match3','sudoku','words') THEN
   RAISE EXCEPTION 'Unknown game type'; END IF;
 IF (SELECT count(*) FROM public.messenger_activities WHERE conversation_id=p_conversation
   AND inviter_id=v_me AND opponent_id=p_opponent AND status='invited' AND created_at>now()-interval '10 minutes')>=3 THEN
   RAISE EXCEPTION 'Too many pending invitations. Wait for a response.'; END IF;
 INSERT INTO public.messenger_activities(conversation_id,game_type,inviter_id,opponent_id,turn_id)
 VALUES(p_conversation,v_kind,v_me,p_opponent,v_me) RETURNING id INTO v_room;
 IF v_kind='mines' THEN
   SELECT array_agg(cell ORDER BY cell) INTO v_mines FROM (
     SELECT cell FROM generate_series(0,63) cell ORDER BY random() LIMIT 10
   ) picks;
   INSERT INTO public.messenger_activity_secrets(activity_id,mine_cells) VALUES(v_room,v_mines);
 END IF;
 RETURN v_room;
END $fn$;

CREATE OR REPLACE FUNCTION public.messenger_answer_game(p_activity uuid,p_accept boolean)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $fn$
DECLARE v_room public.messenger_activities%ROWTYPE;
BEGIN
 SELECT * INTO v_room FROM public.messenger_activities WHERE id=p_activity FOR UPDATE;
 IF NOT FOUND OR v_room.status<>'invited' OR v_room.opponent_id IS DISTINCT FROM auth.uid()
    OR NOT public.is_member(v_room.conversation_id,auth.uid()) THEN
   RAISE EXCEPTION 'This invitation is unavailable' USING ERRCODE='42501'; END IF;
 IF p_accept AND NOT public.moderation_can_send(auth.uid()) THEN
   RAISE EXCEPTION 'Your account cannot participate in games' USING ERRCODE='42501'; END IF;
 UPDATE public.messenger_activities SET status=CASE WHEN p_accept THEN 'active' ELSE 'declined' END, updated_at=now() WHERE id=p_activity;
END $fn$;

CREATE OR REPLACE FUNCTION public.messenger_game_move(p_activity uuid,p_action jsonb)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $fn$
DECLARE
 v_room public.messenger_activities%ROWTYPE;
 v_me uuid := auth.uid(); v_cell int; v_col int; v_hit boolean; v_out jsonb :=p_action;
 v_winner uuid; v_finished boolean:=false; v_board text; v_rec record;
 v_mark text; v_line int[]; v_idx int; v_row int; v_colnum int;
 v_hits_a int; v_hits_b int; v_allowed text[]; v_from int; v_to int; v_solution text:='534678912672195348198342567859761423426853791713924856961537284287419635345286179';
 v_puzzle text:='530070000600195000098000060800060003400803001700020006060000280000419005000080079';
 v_turn_based boolean;
BEGIN
 SELECT * INTO v_room FROM public.messenger_activities WHERE id=p_activity FOR UPDATE;
 IF NOT FOUND OR v_room.status<>'active' OR v_me IS NULL OR v_me NOT IN(v_room.inviter_id,v_room.opponent_id)
    OR NOT public.is_member(v_room.conversation_id,v_me) OR NOT public.moderation_can_send(v_me) THEN
   RAISE EXCEPTION 'Not allowed to play this game' USING ERRCODE='42501'; END IF;
 IF jsonb_typeof(p_action) <> 'object' OR pg_column_size(p_action)>2048 THEN RAISE EXCEPTION 'Invalid move'; END IF;
 IF v_room.move_number>=1000 THEN RAISE EXCEPTION 'Game has reached its move limit. Start a rematch.'; END IF;
 v_turn_based:=v_room.game_type IN ('tictactoe','checkers','mines','connect4','chess','colourclash');
 IF v_turn_based AND v_room.turn_id IS DISTINCT FROM v_me THEN RAISE EXCEPTION 'Wait for your turn'; END IF;
 IF v_room.game_type='tictactoe' THEN
   IF (coalesce(p_action->>'kind',''))<>'cell' OR (coalesce(p_action->>'cell','')) !~ '^[0-8]$' THEN RAISE EXCEPTION 'Invalid square'; END IF;
   v_cell:=(coalesce(p_action->>'cell',''))::int;
   IF EXISTS(SELECT 1 FROM public.messenger_activity_moves WHERE activity_id=p_activity AND action->>'cell'=v_cell::text) THEN RAISE EXCEPTION 'Square is occupied'; END IF;
 ELSIF v_room.game_type='connect4' THEN
   IF (coalesce(p_action->>'kind',''))<>'column' OR (coalesce(p_action->>'column','')) !~ '^[0-6]$' THEN RAISE EXCEPTION 'Invalid column'; END IF;
   v_col:=(coalesce(p_action->>'column',''))::int;
   IF (SELECT count(*) FROM public.messenger_activity_moves WHERE activity_id=p_activity AND action->>'column'=v_col::text)>=6 THEN RAISE EXCEPTION 'Column is full'; END IF;
 ELSIF v_room.game_type='mines' THEN
   IF (coalesce(p_action->>'kind',''))<>'flag' OR (coalesce(p_action->>'cell','')) !~ '^([0-9]|[1-5][0-9]|6[0-3])$' THEN RAISE EXCEPTION 'Invalid flag'; END IF;
   v_cell:=(coalesce(p_action->>'cell',''))::int;
   IF EXISTS(SELECT 1 FROM public.messenger_activity_moves WHERE activity_id=p_activity AND action->>'cell'=v_cell::text) THEN RAISE EXCEPTION 'Already flagged'; END IF;
   SELECT v_cell=ANY(s.mine_cells) INTO v_hit FROM public.messenger_activity_secrets s WHERE activity_id=p_activity;
   v_out:=v_out || jsonb_build_object('hit',COALESCE(v_hit,false));
 ELSIF v_room.game_type IN ('checkers','chess','match3') THEN
   IF (coalesce(p_action->>'kind','')) NOT IN ('move','swap') OR
      (coalesce(p_action->>'from','')) !~ '^([0-9]|[1-5][0-9]|6[0-3])$' OR
      (coalesce(p_action->>'to','')) !~ '^([0-9]|[1-5][0-9]|6[0-3])$' OR
      p_action->>'from'=p_action->>'to' THEN RAISE EXCEPTION 'Invalid board move'; END IF;
   v_from:=(coalesce(p_action->>'from',''))::int;
   v_to:=(coalesce(p_action->>'to',''))::int;
   IF v_room.game_type='match3' AND NOT (
       (abs(v_from-v_to)=6) OR (abs(v_from-v_to)=1 AND v_from/6=v_to/6)
     ) THEN RAISE EXCEPTION 'Swap adjacent gems only'; END IF;
   IF v_room.game_type='checkers' AND NOT (
       abs(v_from/8-v_to/8) IN (1,2) AND abs(mod(v_from,8)-mod(v_to,8))=abs(v_from/8-v_to/8)
     ) THEN RAISE EXCEPTION 'Checkers move must be diagonal'; END IF;
 ELSIF v_room.game_type='colourclash' THEN
   IF (coalesce(p_action->>'kind','')) NOT IN ('play','draw') OR
     ((coalesce(p_action->>'kind',''))='play' AND (coalesce(p_action->>'card','')) !~ '^([0-9]|[1-3][0-9])$') THEN RAISE EXCEPTION 'Invalid card action'; END IF;
 ELSIF v_room.game_type='solitaire' THEN
   IF (coalesce(p_action->>'kind','')) NOT IN ('collect','draw') OR
    ((coalesce(p_action->>'kind',''))='collect' AND (coalesce(p_action->>'card','')) !~ '^([0-9]|[1-4][0-9]|5[01])$') THEN RAISE EXCEPTION 'Invalid card'; END IF;
 ELSIF v_room.game_type='sudoku' THEN
   IF (coalesce(p_action->>'kind',''))<>'fill' OR (coalesce(p_action->>'cell','')) !~ '^([0-9]|[1-7][0-9]|80)$' OR
      (coalesce(p_action->>'digit','')) !~ '^[1-9]$' THEN RAISE EXCEPTION 'Invalid Sudoku entry'; END IF;
   v_cell:=(coalesce(p_action->>'cell',''))::int;
   IF substring(v_puzzle from v_cell+1 for 1)<>'0' OR
      substring(v_solution from v_cell+1 for 1)<>(coalesce(p_action->>'digit','')) THEN RAISE EXCEPTION 'Incorrect Sudoku entry'; END IF;
   IF EXISTS(SELECT 1 FROM public.messenger_activity_moves WHERE activity_id=p_activity AND player_id=v_me
      AND action->>'cell'=v_cell::text) THEN RAISE EXCEPTION 'Square already solved'; END IF;
 ELSIF v_room.game_type='words' THEN
   IF (coalesce(p_action->>'kind',''))<>'word' OR (coalesce(p_action->>'word','')) !~ '^[a-z]{3,12}$' THEN RAISE EXCEPTION 'Invalid word'; END IF;
   v_allowed:=CASE mod(v_room.seed,3)
     WHEN 0 THEN ARRAY['stream','line','steam','stare','smile','mine','name','mean','main','meal','real','mile','mist','seat','east','team','tear','time','lime','same','sale','isle','slime','term','lean','learn','near','rail','rain','rate','late','least','master','remain','tire','rise','stir','star','merit','tame','metal','train','marine','retail','strain']
     WHEN 1 THEN ARRAY['friend','ship','fish','find','fine','hide','ride','rise','side','spin','pine','shine','spend','send','dish','red','den','pin','dip','hen','end','his','hers','her','rip','fire','siren','pride','spider']
     WHEN 2 THEN ARRAY['conversation','version','voice','stone','note','tone','vote','oven','over','ocean','cone','coat','cove','rest','store','star','rise','train','stove','roast','rain','coin','care','near','nose','sore','save','cater','rave','race','react','cart','iron','ones','vast','vase']
     ELSE ARRAY[]::text[] END;
   IF NOT ((coalesce(p_action->>'word',''))=ANY(v_allowed)) THEN RAISE EXCEPTION 'Word is not in this puzzle'; END IF;
   IF EXISTS(SELECT 1 FROM public.messenger_activity_moves WHERE activity_id=p_activity AND player_id=v_me
       AND action->>'word'=p_action->>'word') THEN RAISE EXCEPTION 'Already used that word'; END IF;
 END IF;
 INSERT INTO public.messenger_activity_moves(activity_id,seq,player_id,action)
 VALUES(p_activity,v_room.move_number+1,v_me,v_out);

 -- Server-authoritative completion for the three simple board/flag games.
 IF v_room.game_type='tictactoe' THEN
   v_board:='.........';
   FOR v_rec IN SELECT player_id,action->>'cell' AS square FROM public.messenger_activity_moves
       WHERE activity_id=p_activity ORDER BY seq LOOP
     v_mark:=CASE WHEN v_rec.player_id=v_room.inviter_id THEN 'X' ELSE 'O' END;
     v_board:=overlay(v_board placing v_mark from v_rec.square::int+1 for 1);
   END LOOP;
   FOREACH v_line SLICE 1 IN ARRAY ARRAY[[1,2,3],[4,5,6],[7,8,9],[1,4,7],[2,5,8],[3,6,9],[1,5,9],[3,5,7]] LOOP
     v_mark:=substring(v_board from v_line[1] for 1);
     IF v_mark<>'.' AND v_mark=substring(v_board from v_line[2] for 1)
       AND v_mark=substring(v_board from v_line[3] for 1) THEN
       v_winner:=CASE WHEN v_mark='X' THEN v_room.inviter_id ELSE v_room.opponent_id END;
       v_finished:=true; EXIT;
     END IF;
   END LOOP;
   IF position('.' in v_board)=0 THEN v_finished:=true; END IF;
 ELSIF v_room.game_type='mines' THEN
   SELECT count(*) FILTER (WHERE player_id=v_room.inviter_id AND (action->>'hit')='true'),
          count(*) FILTER (WHERE player_id=v_room.opponent_id AND (action->>'hit')='true')
   INTO v_hits_a,v_hits_b FROM public.messenger_activity_moves WHERE activity_id=p_activity;
   IF v_hits_a+v_hits_b>=10 THEN
     v_finished:=true;
     v_winner:=CASE WHEN v_hits_a>v_hits_b THEN v_room.inviter_id
                    WHEN v_hits_b>v_hits_a THEN v_room.opponent_id ELSE NULL END;
   END IF;
 ELSIF v_room.game_type='connect4' THEN
   v_board:=repeat('.',42);
   FOR v_rec IN SELECT player_id,action->>'column' AS col FROM public.messenger_activity_moves
      WHERE activity_id=p_activity ORDER BY seq LOOP
     v_colnum:=v_rec.col::int;
     v_row:=5;
     LOOP
       EXIT WHEN v_row<0;
       v_idx:=v_row*7+v_colnum+1;
       IF substring(v_board from v_idx for 1)='.' THEN
         v_mark:=CASE WHEN v_rec.player_id=v_room.inviter_id THEN 'X' ELSE 'O' END;
         v_board:=overlay(v_board placing v_mark from v_idx for 1);
         EXIT;
       END IF;
       v_row:=v_row-1;
     END LOOP;
   END LOOP;
   FOR v_row IN 0..5 LOOP
     FOR v_colnum IN 0..6 LOOP
       v_idx:=v_row*7+v_colnum+1;
       v_mark:=substring(v_board from v_idx for 1);
       IF v_mark<>'.' AND (
          (v_colnum<=3 AND v_mark=substring(v_board from v_idx+1 for 1)
              AND v_mark=substring(v_board from v_idx+2 for 1)
              AND v_mark=substring(v_board from v_idx+3 for 1))
          OR (v_row<=2 AND v_mark=substring(v_board from v_idx+7 for 1)
              AND v_mark=substring(v_board from v_idx+14 for 1)
              AND v_mark=substring(v_board from v_idx+21 for 1))
          OR (v_row<=2 AND v_colnum<=3 AND v_mark=substring(v_board from v_idx+8 for 1)
              AND v_mark=substring(v_board from v_idx+16 for 1)
              AND v_mark=substring(v_board from v_idx+24 for 1))
          OR (v_row<=2 AND v_colnum>=3 AND v_mark=substring(v_board from v_idx+6 for 1)
              AND v_mark=substring(v_board from v_idx+12 for 1)
              AND v_mark=substring(v_board from v_idx+18 for 1))
       ) THEN
         v_finished:=true;
         v_winner:=CASE WHEN v_mark='X' THEN v_room.inviter_id ELSE v_room.opponent_id END;
         EXIT;
       END IF;
     END LOOP;
     EXIT WHEN v_finished;
   END LOOP;
   IF position('.' in v_board)=0 THEN v_finished:=true; END IF;
 END IF;
 UPDATE public.messenger_activities SET move_number=move_number+1,
   turn_id=CASE WHEN v_finished THEN NULL WHEN v_turn_based THEN
     (CASE WHEN v_me=inviter_id THEN opponent_id ELSE inviter_id END) ELSE turn_id END,
   status=CASE WHEN v_finished THEN 'finished' ELSE status END,
   winner_id=CASE WHEN v_finished THEN v_winner ELSE winner_id END,
   updated_at=now() WHERE id=p_activity;
 RETURN v_out;
END $fn$;

CREATE OR REPLACE FUNCTION public.messenger_finish_game(p_activity uuid,p_winner uuid DEFAULT NULL)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $fn$
DECLARE v_room public.messenger_activities%ROWTYPE;
BEGIN
 SELECT * INTO v_room FROM public.messenger_activities WHERE id=p_activity FOR UPDATE;
 IF NOT FOUND OR v_room.status<>'active' OR auth.uid() NOT IN(v_room.inviter_id,v_room.opponent_id)
    OR NOT public.is_member(v_room.conversation_id,auth.uid()) THEN
    RAISE EXCEPTION 'Cannot finish this game' USING ERRCODE='42501'; END IF;
 -- A participant can concede only to their opponent; draw is also allowed.
 IF p_winner IS NOT NULL AND p_winner <> (CASE WHEN auth.uid()=v_room.inviter_id THEN v_room.opponent_id ELSE v_room.inviter_id END) THEN
    RAISE EXCEPTION 'You can only concede to your opponent'; END IF;
 UPDATE public.messenger_activities SET status='finished',winner_id=p_winner,updated_at=now() WHERE id=p_activity;
END $fn$;

