DROP POLICY IF EXISTS "conversation participants view activities" ON public.messenger_activities;
CREATE POLICY "conversation participants view activities" ON public.messenger_activities FOR SELECT TO authenticated
USING (public.is_member(conversation_id,(SELECT auth.uid())));

