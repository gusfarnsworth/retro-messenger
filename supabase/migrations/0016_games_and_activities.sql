-- Keep large whiteboards from turning into unbounded write-amplification or storage spam.
CREATE OR REPLACE FUNCTION public.messenger_validate_stroke()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $fn$
DECLARE v_point jsonb;
BEGIN
 IF NEW.author_id IS DISTINCT FROM auth.uid() OR NOT public.can_message(NEW.conversation_id,auth.uid()) THEN
   RAISE EXCEPTION 'Not allowed to draw in this conversation' USING ERRCODE='42501'; END IF;
 IF (SELECT count(*) FROM public.messenger_whiteboard_strokes
     WHERE conversation_id=NEW.conversation_id AND author_id=NEW.author_id
       AND created_at>now()-interval '60 seconds')>=90 THEN
   RAISE EXCEPTION 'Too many strokes. Try again shortly.'; END IF;
 FOR v_point IN SELECT value FROM jsonb_array_elements(NEW.points) LOOP
   IF jsonb_typeof(v_point)<>'array' OR jsonb_array_length(v_point)<>2 OR
      COALESCE(v_point->>0,'') !~ '^[0-9]{1,3}$' OR
      COALESCE(v_point->>1,'') !~ '^[0-9]{1,3}$' OR
      (v_point->>0)::int > 720 OR (v_point->>1)::int > 420 THEN
      RAISE EXCEPTION 'Invalid drawing coordinates'; END IF;
 END LOOP;
 RETURN NEW;
END $fn$;
REVOKE ALL ON FUNCTION public.messenger_validate_stroke() FROM PUBLIC,anon,authenticated;
